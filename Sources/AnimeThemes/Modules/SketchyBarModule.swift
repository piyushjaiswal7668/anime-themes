import Foundation

/// Recolors SketchyBar (an optional custom menu bar). Does nothing if SketchyBar isn't installed.
/// The bar layout lives in ~/.config/sketchybar/sketchybarrc (installed by `install.sh --with-sketchybar`);
/// it reads the colors this module writes.
enum SketchyBarModule {
    static func binary() -> String? {
        ["/opt/homebrew/bin/sketchybar", "/usr/local/bin/sketchybar"]
            .first { FileManager.default.isExecutableFile(atPath: $0) }
    }

    static var isInstalled: Bool { binary() != nil }

    static func apply(_ v: Variant) throws {
        guard let bin = binary() else { return }
        let c = v.spec.colors
        func argb(_ hex: String, alpha: String = "ff") -> String {
            "0x" + alpha + hex.replacingOccurrences(of: "#", with: "")
        }
        let script = """
        # Generated by Anime Themes
        export BAR_COLOR=\(argb(c.bg, alpha: "e6"))
        export ITEM_BG=\(argb(c.surface))
        export ACCENT=\(argb(c.accent))
        export ACCENT2=\(argb(c.accent2))
        export FG=\(argb(c.fg))
        export MUTED=\(argb(c.muted))
        export THEME_EMOJI='\(v.spec.emoji)'
        export THEME_NAME='\(v.spec.name.replacingOccurrences(of: "'", with: ""))'

        """
        let dir = Paths.shellActive
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try script.write(to: dir.appendingPathComponent("sketchybar-colors.sh"), atomically: true, encoding: .utf8)
        try Run.run(bin, ["--reload"])
    }
}
