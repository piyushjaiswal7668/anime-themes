import Foundation

/// Writes the files the zsh hook reads (~/.config/anime-themes/active).
/// Open terminal windows pick up the change at their next prompt.
enum ShellModule {
    static func apply(_ v: Variant, settings: Settings) throws {
        let fm = FileManager.default
        let dir = Paths.shellActive
        try fm.createDirectory(at: dir, withIntermediateDirectories: true)

        // Aliases: the anime's shared set, then the variant's extras.
        var aliases = "# Generated by Anime Themes from your theme pack. Edit the pack, not this file.\n"
        for url in [v.animeFolder.appendingPathComponent("aliases.zsh"), v.folder.appendingPathComponent("aliases.zsh")] {
            if let text = try? String(contentsOf: url, encoding: .utf8) { aliases += text + "\n" }
        }
        try aliases.write(to: dir.appendingPathComponent("aliases.zsh"), atomically: true, encoding: .utf8)

        for name in ["logo.txt", "lines.txt"] {
            let src = v.folder.appendingPathComponent(name)
            let dst = dir.appendingPathComponent(name)
            try? fm.removeItem(at: dst)
            if fm.fileExists(atPath: src.path) { try fm.copyItem(at: src, to: dst) }
        }

        let c = v.spec.colors
        let ansi = c.ansi16
        func idx(_ hex: String) -> Int { RGB.of(hex).xterm256 }
        let env = """
        # Generated by Anime Themes. Edit the theme pack instead.
        ANIME_THEME=\(q(v.id))
        ANIME_ANIME=\(q(v.anime.name))
        ANIME_NAME=\(q(v.spec.name))
        ANIME_CHARACTER=\(q(v.spec.character))
        ANIME_EMOJI=\(q(v.spec.emoji))
        ANIME_PROMPT_USER=\(q(v.spec.promptUser))
        ANIME_PROMPT_HOST=\(q(v.spec.promptHost))
        ANIME_C_ACCENT=\(idx(c.accent))
        ANIME_C_ACCENT2=\(idx(c.accent2))
        ANIME_C_ACCENT3=\(idx(c.accent3))
        ANIME_C_FG=\(idx(c.fg))
        ANIME_C_MUTED=\(idx(c.muted))
        ANIME_C_RED=\(idx(ansi[9]))
        ANIME_VOICE=\(settings.voice ? 1 : 0)
        ANIME_VOICE_ROOT=\(q(v.folder.appendingPathComponent("voice").path))
        ANIME_VOICE_LANGS=\(q(settings.languageOrder.joined(separator: " ")))
        ANIME_VOICE_VOLUME=\(String(format: "%.2f", settings.volume))

        """
        try env.write(to: dir.appendingPathComponent("env.zsh"), atomically: true, encoding: .utf8)

        // Written last: the hook reloads when this value changes.
        try String(Date().timeIntervalSince1970).write(to: dir.appendingPathComponent("stamp"),
                                                       atomically: true, encoding: .utf8)
    }

    /// Single-quotes a value for zsh.
    private static func q(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
